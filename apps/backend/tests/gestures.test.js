// NOTE: these use SYNTHETIC landmarks. They prove the rules behave as designed; they are NOT evidence of real-world
// recognition accuracy. Real-world evaluation protocol: docs/EVALUATION.md (scripts/eval-gestures.js).
const test = require('node:test'), assert = require('node:assert');
const fs = require('fs'), os = require('os'), path = require('path');
const G = require('@echoclass/shared/gestures').default;
const { evaluateFile } = require('../scripts/eval-gestures');

function hand(ext = {}, { thumbDir = 'side', pinchIndex = false } = {}) {
  const P = (x, y) => ({ x, y, z: 0 }), lm = Array(21);
  lm[0] = P(0.5, 0.8);
  const xs = { index: 0.44, middle: 0.5, ring: 0.56, pinky: 0.62 }, base = { index: [5, 6, 7, 8], middle: [9, 10, 11, 12], ring: [13, 14, 15, 16], pinky: [17, 18, 19, 20] };
  const mcpY = { index: 0.62, middle: 0.6, ring: 0.62, pinky: 0.66 };
  for (const k of Object.keys(base)) {
    const [m, p, dI, t] = base[k], x = xs[k], y = mcpY[k]; lm[m] = P(x, y);
    if (ext[k]) { lm[p] = P(x, y - 0.07); lm[dI] = P(x, y - 0.13); lm[t] = P(x, y - 0.19); } else { lm[p] = P(x, y - 0.05); lm[dI] = P(x, y); lm[t] = P(x, y + 0.05); }
  }
  lm[1] = P(0.45, 0.76); lm[2] = P(0.41, 0.72);
  if (ext.thumb) {
    if (thumbDir === 'up') { lm[3] = P(0.39, 0.6); lm[4] = P(0.38, 0.45); } else if (thumbDir === 'down') { lm[3] = P(0.39, 0.86); lm[4] = P(0.38, 1.0); } else { lm[3] = P(0.34, 0.69); lm[4] = P(0.26, 0.65); }
  } else { lm[3] = P(0.45, 0.68); lm[4] = P(0.47, 0.64); }
  if (pinchIndex) lm[8] = P(lm[4].x + 0.01, lm[4].y - 0.01);
  return lm;
}
const all = { thumb: 1, index: 1, middle: 1, ring: 1, pinky: 1 };
const CASES = [
  ['HELLO', hand(all)], ['FIST', hand({})], ['POINT', hand({ index: 1 })], ['PEACE', hand({ index: 1, middle: 1 })], ['THREE', hand({ index: 1, middle: 1, ring: 1 })],
  ['FOUR', hand({ index: 1, middle: 1, ring: 1, pinky: 1 })], ['L', hand({ thumb: 1, index: 1 })], ['HELP', hand({ thumb: 1, pinky: 1 })], ['ILY', hand({ thumb: 1, index: 1, pinky: 1 })],
  ['THUMBS_UP', hand({ thumb: 1 }, { thumbDir: 'up' })], ['THUMBS_DOWN', hand({ thumb: 1 }, { thumbDir: 'down' })], ['OK', hand({ middle: 1, ring: 1, pinky: 1 }, { pinchIndex: true })],
];

test('every registered gesture has a synthetic example that classifies correctly with clear margin', () => {
  assert.deepEqual(CASES.map(c => c[0]).sort(), Object.keys(G.DEFAULTS).sort());
  for (const [name, lm] of CASES) { const r = G.evaluate(lm); assert.equal(r.gesture, name); assert.equal(r.status, 'recognised', name + ' clarity ' + r.clarity); assert.ok(r.clarity >= 0.25 && r.clarity <= 1); assert.equal(G.classify(lm), name); }
});

test('registry documents every gesture (label, phrase, hand configuration, limitations) and states it is not a validated sign language', () => {
  for (const [k, v] of Object.entries(G.DEFAULTS)) for (const f of ['label', 'phrase', 'hand', 'limits']) assert.ok(typeof v[f] === 'string' && v[f].length >= 2, `${k}.${f}`);
  assert.match(G.CONTEXT, /NOT validated signs/);
  assert.match(fs.readFileSync(path.join(__dirname, '..', '..', '..', 'docs', 'GESTURES.md'), 'utf8'), /Generated by/);
});

test('no hand / malformed landmarks are reported as no_hand, never as a gesture', () => {
  for (const bad of [null, undefined, [], 'x', Array(20).fill({ x: 0, y: 0 }), Array(21).fill(null), Array(21).fill({ x: NaN, y: 0 })]) { const r = G.evaluate(bad); assert.equal(r.status, 'no_hand'); assert.equal(r.gesture, null); }
  assert.equal(G.classify(null), null);
});

test('a hand that is too small in frame is not classified', () => {
  const tiny = hand(all).map(p => ({ x: 0.5 + (p.x - 0.5) * 0.05, y: 0.5 + (p.y - 0.8) * 0.05, z: 0 }));
  assert.equal(G.evaluate(tiny).status, 'too_small');
});

test('unsupported shapes are reported as unsupported', () => {
  for (const lm of [hand({ middle: 1 }), hand({ ring: 1 }), hand({ thumb: 1, middle: 1 }), hand({ pinky: 1 }), hand({ index: 1, ring: 1 })]) { const r = G.evaluate(lm); assert.equal(r.status, 'unsupported'); assert.equal(r.gesture, null); }
});

test('ambiguous (half-curled) fingers are borderline and rejected at the default clarity threshold', () => {
  const lm = hand({ index: 1 });
  // curl the index finger part-way so its extension ratio sits right at the decision threshold
  lm[8] = { x: 0.44, y: 0.62 - 0.095, z: 0 }; lm[7] = { x: 0.44, y: 0.62 - 0.07, z: 0 };
  const r = G.evaluate(lm); assert.ok(r.gesture === null || r.status === 'borderline', JSON.stringify({ s: r.status, g: r.gesture, c: r.clarity }));
  const strict = G.evaluate(hand({ index: 1 }), { minClarity: 1.1 }); assert.equal(strict.status, 'borderline');   // clarity gate works
});

test('rotation tolerance (not for thumbs up/down, which are image-orientation based and documented as such)', () => {
  const rot = (lm, a) => lm.map(p => { const x = p.x - 0.5, y = p.y - 0.7; return { x: 0.5 + x * Math.cos(a) - y * Math.sin(a), y: 0.7 + x * Math.sin(a) + y * Math.cos(a), z: 0 }; });
  for (const [name, lm] of CASES.filter(c => !c[0].startsWith('THUMBS'))) assert.equal(G.classify(rot(lm, 0.5)), name, name + ' rotated');
});

test('tracker needs a steady hold, fires once, ignores flicker, re-arms after another sign or the hand leaving', () => {
  const t = G.createTracker({ hold: 3, release: 2 }), fired = [];
  for (const g of ['A', 'A', 'B', 'B', 'B', 'B', 'B']) { const r = t.push(g); if (r) fired.push(r); }
  assert.deepEqual(fired, ['B']);
  for (const g of ['B', 'B', null, 'B', 'B', 'B', 'B']) { const r = t.push(g); if (r) fired.push(r); }   // single dropout does not re-fire
  assert.deepEqual(fired, ['B']);
  t.push(null); t.push(null); for (const g of ['B', 'B', 'B']) { const r = t.push(g); if (r) fired.push(r); }
  assert.deepEqual(fired, ['B', 'B']);
  const u = G.createTracker({ hold: 3 }), out = []; for (const g of ['A', 'A', 'A', 'B', 'B', 'B', 'A', 'A', 'A']) { const r = u.push(g); if (r) out.push(r); } assert.deepEqual(out, ['A', 'B', 'A']);
});

test('classifier interface is swappable', () => {
  assert.equal(G.createClassifier('geometric').name, 'geometric');
  G.registerClassifier('stub', () => ({ name: 'stub', evaluate: () => ({ status: 'recognised', gesture: 'HELLO', clarity: 1 }) }));
  assert.equal(G.createClassifier('stub').evaluate([]).gesture, 'HELLO');
  assert.throws(() => G.createClassifier('missing'), /Unknown classifier/);
});

test('evaluation script computes precision/recall/confusion/false-positive rate from labelled data (format check on SYNTHETIC rows)', () => {
  const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'eval-')), 's.jsonl');
  const rows = [...CASES.map(([label, lm], i) => ({ label, person: 'synthetic' + (i % 2), landmarks: lm })), { label: 'NONE', person: 'synthetic0', landmarks: hand({ middle: 1 }) }, { label: 'POINT', person: 'synthetic1', landmarks: hand({ index: 1, middle: 1 }) }];
  fs.writeFileSync(f, rows.map(r => JSON.stringify(r)).join('\n'));
  const r = evaluateFile(f); assert.equal(r.samples, 14); assert.equal(r.falsePositiveRateOnNone, 0);
  assert.equal(r.confusionMatrix.POINT.PEACE, 1); assert.equal(r.perClass.find(s => s.label === 'POINT').recall, 0.5);
  assert.throws(() => { fs.writeFileSync(f, 'nope'); evaluateFile(f); }, /not valid JSON/);
});
